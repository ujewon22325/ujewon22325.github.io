// Keep a working static fallback for repositories still publishing main directly.
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, copyFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const marker = '<!-- Generated by npm run stage:static; edit src/index.html instead. -->';
const destination = resolve(root, 'index.html');
if (existsSync(destination) && !readFileSync(destination, 'utf8').startsWith(marker)) {
  throw new Error('Public index.html is not a recognized generated file; preserve it before staging.');
}
const html = readFileSync(resolve(root, 'dist/index.html'), 'utf8');
if (!html.includes('/cardwise/assets/')) throw new Error('Build base must be /cardwise/.');
const assets = resolve(root, 'assets');
mkdirSync(assets, { recursive: true });
for (const entry of readdirSync(resolve(root, 'dist/assets'), { withFileTypes: true })) {
  if (!entry.isFile()) throw new Error('Unexpected asset directory.');
  const source = resolve(root, 'dist/assets', entry.name);
  const target = resolve(assets, entry.name);
  if (existsSync(target) && !readFileSync(source).equals(readFileSync(target))) throw new Error('Conflicting immutable asset: ' + entry.name);
  copyFileSync(source, target);
}
writeFileSync(destination, marker + '\n' + html);
console.log('Staged CardWise index.html and bundled assets for static branch publishing.');
